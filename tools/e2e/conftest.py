class PageSpeedClient:
    """HTTP client wrapping requests.Session with PageSpeed helpers."""

    def __init__(self, base_url: str):
        self.base_url = base_url
        self.session = requests.Session()

    def get(self, path: str, headers: dict[str, str] | None = None, **kwargs):
        """GET request to nginx."""
        url = self.base_url + path
        return self.session.get(url, headers=headers or {}, **kwargs)

    def poll_for_hit(
        self,
        path: str,
        timeout: float = 60.0,
        interval: float = 0.5,
        headers: dict[str, str] | None = None,
        expect_smaller_than: int = 0,
    ) -> requests.Response:
        """Poll until X-PageSpeed: HIT is returned, or timeout.

        This accounts for the worker needing time to process the
        notification and write the optimized variant to cache.

        If expect_smaller_than > 0, keeps polling until the response
        body is smaller than this value (to wait for the optimized
        variant rather than accepting the original from cache fallback).
        """
        deadline = time.time() + timeout
        last_response = None
        while time.time() < deadline:
            try:
                resp = self.get(path, headers=headers)
                last_response = resp
                if resp.headers.get("X-PageSpeed") == "HIT":
                    if expect_smaller_than > 0:
                        if len(resp.content) < expect_smaller_than:
                            return resp
                        # HIT but still original size, keep polling
                    else:
                        return resp
            except requests.RequestException:
                pass  # Transient network error, retry
            time.sleep(interval)
        # Return last response even if not a HIT (test can assert on it)
        assert last_response is not None, f"No response received for {path}"
        return last_response

    @staticmethod
    def assert_miss(response: requests.Response):
        """Assert response has X-PageSpeed: MISS header."""
        assert response.headers.get("X-PageSpeed") == "MISS", (
            f"Expected X-PageSpeed: MISS, "
            f"got: {response.headers.get('X-PageSpeed', '<absent>')}"
        )

    @staticmethod
    def assert_hit(response: requests.Response):
        """Assert response has X-PageSpeed: HIT header."""
        assert response.headers.get("X-PageSpeed") == "HIT", (
            f"Expected X-PageSpeed: HIT, "
            f"got: {response.headers.get('X-PageSpeed', '<absent>')}"
        )


def poll_for_variant(
    client: PageSpeedClient,
    path: str,
    headers: dict[str, str] | None = None,
    timeout: float = 20.0,
    interval: float = 0.5,
) -> requests.Response | None:
    """Poll until a HIT with non-empty content is returned.

    Useful for waiting for proactive variants (viewport, density,
    save-data) to be generated by the worker.
    """
    deadline = time.time() + timeout
    last = None
    while time.time() < deadline:
        try:
            r = client.get(path, headers=headers)
            last = r
            if r.headers.get("X-PageSpeed") == "HIT" and len(r.content) > 0:
                return r
        except requests.RequestException:
            pass
        time.sleep(interval)
    return last


def compose_run(*args):
    """Run docker compose command."""
    return subprocess.run(
        ["docker", "compose", "-f", COMPOSE_FILE, *args],
        capture_output=True,
        text=True,
    )


def compose_check(*args):
    """Run docker compose command, raising on failure."""
    return subprocess.run(
        ["docker", "compose", "-f", COMPOSE_FILE, *args],
        capture_output=True,
        text=True,
        check=True,
    )


def docker_exec(service: str, command: str | list[str]) -> subprocess.CompletedProcess:
    """Run a command in a running Docker Compose service container.

    The command can be a simple string (split on whitespace) or a list
    of arguments for commands that contain spaces or special characters.
    """
    if isinstance(command, str):
        cmd_parts = command.split()
    else:
        cmd_parts = command
    return subprocess.run(
        ["docker", "compose", "-f", COMPOSE_FILE, "exec", "-T", service] + cmd_parts,
        capture_output=True,
        text=True,
    )


def _wait_for_nginx(url: str, timeout: float = STARTUP_TIMEOUT):
    """Wait for nginx to respond with a 2xx/3xx status."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            r = requests.get(url + "/", timeout=2)
            if r.status_code < 500:
                return
        except requests.RequestException:
            pass
        time.sleep(1)
    raise TimeoutError(f"Nginx not ready at {url} after {timeout}s")


