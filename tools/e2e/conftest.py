class WorkerApiClient:
    """HTTP client for the worker's /v1/* API."""

    def __init__(self, base_url: str, token: str = WORKER_API_TOKEN):
        self.base_url = base_url
        self.session = requests.Session()
        if token:
            self.session.headers["Authorization"] = f"Bearer {token}"

    def get_health(self) -> dict:
        """GET /v1/health and return parsed JSON."""
        r = self.session.get(f"{self.base_url}/v1/health", timeout=5)
        r.raise_for_status()
        return r.json()

    def get_config(self) -> dict:
        """GET /v1/config and return parsed JSON."""
        r = self.session.get(f"{self.base_url}/v1/config", timeout=5)
        r.raise_for_status()
        return r.json()

    def patch_config(self, **kwargs) -> dict:
        """PATCH /v1/config with given fields and return parsed JSON response.

        Returns dict with keys: applied, rejected, warnings, config.
        """
        r = self.session.patch(
            f"{self.base_url}/v1/config",
            json=kwargs,
            headers=self._CSRF_HEADERS,
            timeout=10,
        )
        r.raise_for_status()
        return r.json()

    def patch_config_raw(self, body: str) -> requests.Response:
        """PATCH /v1/config with raw string body (for testing malformed JSON)."""
        return self.session.patch(
            f"{self.base_url}/v1/config",
            data=body,
            headers={"Content-Type": "application/json", **self._CSRF_HEADERS},
            timeout=10,
        )

    def get_stats(self) -> dict:
        """GET /v1/stats and return parsed JSON."""
        r = self.session.get(f"{self.base_url}/v1/stats", timeout=5)
        r.raise_for_status()
        return r.json()

    # CSRF headers required by the worker's mutating endpoints (dual-header check).
    _CSRF_HEADERS = {"X-Requested-With": "XMLHttpRequest"}

    def post_raw(self, path: str, json_body: dict | None = None) -> requests.Response:
        """POST an arbitrary /v1/* path with CSRF headers; returns the raw response.

        Used to assert that removed endpoints answer 404 rather than being
        rejected earlier on CSRF or body grounds.
        """
        return self.session.post(
            f"{self.base_url}{path}",
            json=json_body if json_body is not None else {},
            headers=self._CSRF_HEADERS,
            timeout=10,
        )

    def get_raw(self, path: str) -> requests.Response:
        """GET an arbitrary /v1/* path; returns the raw response."""
        return self.session.get(f"{self.base_url}{path}", timeout=10)


def restart_worker(timeout_sec: float = 30.0):
    """Restart worker container and wait for API readiness."""
    compose_check("restart", "worker")
    deadline = time.time() + timeout_sec
    while time.time() < deadline:
        try:
            r = requests.get(f"{WORKER_API_URL}/v1/health", timeout=2)
            if r.status_code == 200:
                return
        except requests.RequestException:
            pass
        time.sleep(0.5)
    raise TimeoutError(f"Worker API not ready at {WORKER_API_URL} after {timeout_sec}s")


def read_container_file(service: str, path: str) -> str | None:
    """Read a file from inside a running container. Returns None if not found."""
    result = docker_exec(service, ["cat", path])
    if result.returncode != 0:
        return None
    return result.stdout


def stat_container_file(service: str, path: str) -> str | None:
    """Get file permissions (octal) from inside a container. Returns None if not found."""
    result = docker_exec(service, ["stat", "-c", "%a", path])
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def unique_url(base_path: str, test_name: str) -> str:
    """Append unique query string for cache isolation between tests."""
    return f"{base_path}?t={test_name}_{int(time.time() * 1000)}"


